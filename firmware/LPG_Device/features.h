// The 9 engineered features, mirroring backend/app/services/lpg_features.py
// (and the trained model's input order). Pure C++ - testable on a PC.
#pragma once

constexpr int FEATURE_COUNT = 9;
// 31 readings: now plus 30 s of history (slope_30s needs ppm[-31]).
constexpr int FEATURE_BUFFER_LEN = 31;

// Order MUST match ml/model_card.json "features". Verify when you add the model.
//   0 ppm_comp   1 d_ppm_5s   2 slope_30s   3 ma10   4 ma30
//   5 temp_c     6 rh_pct     7 d_rh_10s    8 tt700_s
struct FeatureVector {
  float ppm_comp = 0, d_ppm_5s = 0, slope_30s = 0, ma10 = 0, ma30 = 0;
  float temp_c = 0, rh_pct = 0, d_rh_10s = 0, tt700_s = 3600;

  void toArray(float *out) const {
    out[0] = ppm_comp;
    out[1] = d_ppm_5s;
    out[2] = slope_30s;
    out[3] = ma10;
    out[4] = ma30;
    out[5] = temp_c;
    out[6] = rh_pct;
    out[7] = d_rh_10s;
    out[8] = tt700_s;
  }
};

// Circular buffer of the last 31 (ppm, rh) pairs, one pair per second.
class FeatureWindow {
 public:
  void reset();
  void push(float ppm, float rhPct);
  int size() const { return count_; }
  // k = 0 is the newest sample, k = 1 one second ago, ...
  float ppmAgo(int k) const { return ppm_[index(k)]; }
  float rhAgo(int k) const { return rh_[index(k)]; }

  // Needs at least one pushed sample. Behaves exactly like the backend while the
  // window is still filling: deltas/slope are 0 until enough history exists.
  FeatureVector compute(float tempC) const;

 private:
  int index(int k) const {
    return (head_ - 1 - k + 2 * FEATURE_BUFFER_LEN) % FEATURE_BUFFER_LEN;
  }
  float ppm_[FEATURE_BUFFER_LEN] = {0};
  float rh_[FEATURE_BUFFER_LEN] = {0};
  int head_ = 0;   // next write position
  int count_ = 0;  // valid samples, max FEATURE_BUFFER_LEN
};

// Returns the number of failed checks (0 = all good). Expected values were
// generated by running the backend's own Python compute_features().
int featuresSelfTest();
